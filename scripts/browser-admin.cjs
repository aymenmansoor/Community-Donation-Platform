const assert = require('node:assert/strict');
module.exports = async ({ browser, base, capture, check }) => {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'en-GB', timezoneId: 'Asia/Karachi' });
  const page = await context.newPage(); const errors = []; page.on('pageerror', e => errors.push(e.message)); page.on('dialog', dialog => dialog.accept());
  const navigate = async name => {
    const mobile = page.getByRole('button', { name: 'Toggle navigation' });
    if (await mobile.isVisible() && !await page.getByRole('link', { name }).isVisible()) await mobile.click();
    await page.getByRole('link', { name }).click();
  };
  await check('Admin login, statistics, search, suspension, moderation and audit UI', async () => {
    await page.goto(base + '/auth');
    await page.getByRole('button', { name: 'Login Here' }).click();
    await page.getByLabel('Email Address', { exact: true }).fill(process.env.ADMIN_EMAIL);
    await page.getByLabel('Password', { exact: true }).fill(process.env.ADMIN_PASSWORD);
    await page.getByRole('button', { name: 'Login', exact: true }).click();
    await page.getByText('Total users', { exact: true }).waitFor();
    await capture(page, 'admin-overview');
    await page.getByRole('button', { name: 'users', exact: true }).click();
    await page.getByText('Ellis Fern', { exact: true }).waitFor();
    await page.getByLabel('Search users').fill('ellis.requester@example.test');
    await page.getByRole('button', { name: 'Search', exact: true }).click();
    const row = page.getByRole('row').filter({ hasText: 'ellis.requester@example.test' });
    await row.getByRole('button', { name: 'Suspend', exact: true }).click();
    await row.getByRole('button', { name: 'Reactivate', exact: true }).waitFor();
    await row.getByRole('button', { name: 'Reactivate', exact: true }).click();
    await row.getByRole('button', { name: 'Suspend', exact: true }).waitFor();
    await page.getByLabel('Search users').fill('');
    await page.getByRole('button', { name: 'Search', exact: true }).click();
    await page.getByText('Mira Willow', { exact: true }).waitFor();
    await capture(page, 'admin-users');
    await page.getByRole('button', { name: 'donations', exact: true }).click();
    const listing = page.getByRole('row').filter({ hasText: 'Porcelain cup and saucer' });
    await listing.getByRole('button', { name: 'Hide listing' }).click();
    await page.getByLabel('Moderation reason').fill('Fictional demo moderation check.');
    await page.getByRole('button', { name: 'Save moderation' }).click();
    await listing.getByRole('button', { name: 'Restore', exact: true }).waitFor();
    await listing.getByRole('button', { name: 'Restore', exact: true }).click();
    await page.getByLabel('Moderation reason').fill('Fictional review complete; image and description match.');
    await page.getByRole('button', { name: 'Save moderation' }).click();
    await listing.getByRole('button', { name: 'Hide listing' }).waitFor();
    await capture(page, 'admin-donations');
    await page.getByRole('button', { name: 'requests', exact: true }).click();
    await page.getByRole('cell', { name: 'Science textbook collection', exact: true }).waitFor();
    await capture(page, 'admin-requests');
    await page.getByRole('button', { name: 'Audit log', exact: true }).click();
    await page.getByRole('cell', { name: 'admin.donation.published', exact: true }).first().waitFor();
    await capture(page, 'admin-audit');
  });
  await check('Mobile admin navigation, responsive layout and server logout', async () => {
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: 'overview', exact: true }).click();
    await page.getByText('Total users', { exact: true }).waitFor();
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Admin page must not overflow the viewport');
    await capture(page, 'admin-mobile');
    await page.getByRole('button', { name: 'Toggle navigation' }).click();
    await page.getByRole('button', { name: 'Logout', exact: true }).click();
    await page.getByRole('heading', { name: 'Login', exact: true }).waitFor();
    await page.goto(base + '/admin');
    await page.getByRole('heading', { name: 'Create an Account' }).waitFor();
  });
  await check('Mobile requester login, browse and own request history', async () => {
    await page.goto(base + '/auth');
    await page.getByRole('button', { name: 'Login Here' }).click();
    await page.getByLabel('Email Address', { exact: true }).fill('rowan.requester@example.test');
    await page.getByLabel('Password', { exact: true }).fill(process.env.DEMO_PASSWORD);
    await page.getByRole('button', { name: 'Login', exact: true }).click();
    await page.getByRole('heading', { name: 'Welcome, Rowan Vale!' }).waitFor();
    await navigate(/Browse Items/);
    await page.getByRole('heading', { name: 'Available for Request' }).waitFor();
    await page.getByRole('heading', { name: 'Porcelain cup and saucer' }).waitFor();
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Requester browse must fit the viewport');
    await capture(page, 'requester-mobile');
    // Collapse might remain open after route navigation; navigate handles either state.
    await navigate(/My Requests/);
    await page.getByRole('heading', { name: 'My Help Requests' }).waitFor();
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Request table should scroll within its container');
  });
  assert.deepEqual(errors, [], 'Admin/mobile pages have no runtime errors');
  await context.close();
};
